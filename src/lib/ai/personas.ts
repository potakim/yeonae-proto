/** 내담자(사용자) 성별 — 토스 로그인 성별. 프로토타입은 홈의 형/언니 토글 */
export type UserGender = "male" | "female";
export type ByGender<T> = T | { male: T; female: T };
export function pick<T>(v: ByGender<T>, g: UserGender): T {
  return v !== null && typeof v === "object" && !Array.isArray(v) && "male" in (v as object) ? (v as { male: T; female: T })[g] : (v as T);
}
export const genderOfHub = (hub: "형" | "언니"): UserGender => (hub === "언니" ? "female" : "male");

