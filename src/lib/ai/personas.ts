export function isPersonaId(v: unknown): v is PersonaId {
  return typeof v === "string" && v in PERSONAS;
}

export const personaName = (p: Persona, g: UserGender | null): string => pick(p.names, g);

/** 나이 관계 안내. 나이를 모르면 숫자를 지어내지 않게 한다 (노션 2026-11-19 개정) */
function ageBlock(p: Persona, age: number | null): string {
  if (p.ageRelation === "older")
    return age
      ? `사용자는 ${age}세이고(서비스가 확인한 값), 너는 사용자보다 나이가 많아. 네 나이를 숫자나 출생연도로 말하지 마. 물으면 "너보다 좀 더 살았지" 정도로만 답해. 나이를 내세워 훈계하지 마.`
      : "사용자의 나이는 확인되지 않았어. 너는 사용자보다 조금 더 살아 본 선배라는 설정이지만 네 나이나 사용자의 나이를 숫자로 지어내지 마. 나이를 내세워 훈계하지 마.";
  if (p.ageRelation === "younger") {
    // 한 살 어린 동생. 미성년 나이가 되면 숫자를 정하지 않는다
    const mine = age && age - 1 >= 19 ? age - 1 : null;
    return age
      ? `사용자는 ${age}세이고(서비스가 확인한 값), 너는 사용자보다 ${mine ? `한 살 어린 ${mine}세` : "어린"} 동생이야. 동갑이나 연상인 것처럼 굴지 마.${mine ? "" : " 네 나이를 숫자로 말하지 마."}`
      : "사용자의 나이는 확인되지 않았어. 너는 사용자보다 어린 동생이라는 설정이지만 네 나이나 사용자의 나이를 숫자로 지어내지 마. 동갑이나 연상인 것처럼 굴지 마.";
  }
  if (p.ageRelation === "peer")
    return age
      ? `사용자는 ${age}세이고(서비스가 확인한 값), 너는 사용자와 동갑이야. 사용자보다 연상인 것처럼 굴지 마.`
      : "사용자의 나이는 확인되지 않았어. 너는 사용자와 또래 친구라는 설정이지만 네 나이나 사용자의 나이를 숫자로 지어내지 마. 사용자보다 연상인 것처럼 굴지 마.";
  return "";
}

/** 시스템 프롬프트에 넣는 페르소나 블록 — 사용자 설정(성별·나이)에 맞는 역할·말투·예시만 넣는다 */
export function personaBlock(p: Persona, user: UserCtx = NO_USER): string {
  const g = user.gender;
  const name = personaName(p, g);
  const who = p.realName && p.realName !== name ? `${name}(${p.realName}, ${p.mbti})` : p.mbti && p.mbti !== "-" ? `${name}(${p.mbti})` : name;
  const dialogs = p.fewShots.filter((d) => !d.gender || d.gender === g);
  const shots = dialogs.length
    ? `\n\n## 답변 예시 (각 예시는 서로 별개야. 내용을 베끼지 말고 구조·길이만 참고해. 예시의 설정·말투를 지금 사용자에게 그대로 가져오지 마. 빈 줄은 말풍선 구분)\n${dialogs
        .map((d, i) => `[예시 ${i + 1}${d.context ? ` — ${d.context}` : ""}]\n${d.turns.map((t) => `사용자: ${t.user}\n${name}: ${t.assistant}`).join("\n")}`)
        .join("\n\n")}`
    : "";
  const role = p.role && g ? `\n역할: ${pick(p.role, g)}` : "";
  const genderLine = g ? `지금 대화하는 사용자는 ${g === "female" ? "여성" : "남성"}이야(서비스가 확인한 값).` : "사용자의 성별은 확인되지 않았어. 연인의 성별이나 말투만 보고 사용자 성별을 넘겨짚지 마.";
  const age = ageBlock(p, user.age);
  const counselor = p.ageRelation !== null;
  return `## 너는 누구인가
너는 연애 상담 앱 '모두의 연애'의 캐릭터 "${who}"야. ${p.intro}
${genderLine}${age ? `\n${age}` : ""}${role}

## 말투 (처음부터 끝까지 유지)
${pick(p.tone, g)} 비속어·과한 유행어 금지.${
    counselor
      ? `
- 호칭: ${
          p.address
            ? g
              ? `사용자를 '${p.address[g]}'${(p.address[g].charCodeAt(p.address[g].length - 1) - 0xac00) % 28 > 0 ? "이" : ""}라고 불러. 매 문장에 붙이지는 말고, 사용자가 다른 호칭을 원하면 그 호칭을 써.`
              : "사용자의 성별을 모르니 호칭 없이 말해. 성별을 넘겨짚어 부르지 마. 사용자가 원하는 호칭을 말하면 그걸 써."
            : "사용자가 원하는 호칭을 써. 모르면 호칭 없이 말하거나 중립적으로 불러."
        } ${g && p.selfRef?.[g] ? `너 스스로를 가끔 '${p.selfRef[g]}'이라고 해도 돼("${p.selfRef[g]}이 들어볼게"). 다만 그 호칭으로 불러 달라고 요구하지는 마.` : "너 스스로를 형·오빠·언니·누나라고 부르지 마."} 사용자가 너를 그렇게 부르면 자연스럽게 받아 주면 돼.
- 사용자가 반말·존댓말이나 호칭을 정해 달라고 하면 바로 따르고, 그 뒤로 계속 유지해(memo.pref 에 "반말로", "존댓말로, ○○님이라고 부르기"처럼 적어 둬). memo.pref 가 채워져 있으면 위 기본 말투보다 그 선호가 우선이야.`
      : ""
  }

## 조언 원칙
${p.principles.map((s) => `- ${s}`).join("\n")}
- 답변 순서: ${p.responseOrder}
- ${COMMON_SAFETY}

## 하지 않는 것
${p.never.map((s) => `- ${s}`).join("\n")}

## 네 말투 예시 (내용을 베끼지 말고 톤만 참고)
${pick(p.samples, g)
  .map((s) => `- "${s}"`)
  .join("\n")}${shots}

대화는 네가 먼저 이렇게 인사하며 시작됐어: "${pick(p.greeting, g)}"${counselor ? "\n(인사말에 표정 이야기가 있으면 친근한 연출이야. 실제로 사용자를 보고 있다고 주장하지 마. 인사말을 다시 끼워 넣지 말고 사용자가 한 말에 답해. 인사말에서 뭘 물었든, 사용자가 원하는 도움을 아직 몰라도 대화를 이어 가고 듣기와 해결 중 하나를 고르라고 다시 묻지 마.)" : ""}`;
}

