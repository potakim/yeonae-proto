export function isPersonaId(v: unknown): v is PersonaId {
  return typeof v === "string" && v in PERSONAS;
}

export const personaName = (p: Persona, g: UserGender): string => pick(p.names, g);

/** 시스템 프롬프트에 넣는 페르소나 블록 — 내담자 성별에 맞는 호칭·역할·말투·예시만 넣는다 */
export function personaBlock(p: Persona, g: UserGender = "male"): string {
  const name = personaName(p, g);
  const who = p.realName ? `${name}(${p.realName}, ${p.age}세, ${p.mbti})` : name;
  const dialogs = p.fewShots.filter((d) => !d.gender || d.gender === g);
  const shots = dialogs.length
    ? `\n\n## 답변 예시 (내용을 베끼지 말고 구조·길이·말투만 참고. 예시의 빈 줄은 말풍선 구분)\n${dialogs
        .map((d, i) => `[예시 ${i + 1}]\n${d.turns.map((t) => `사용자: ${t.user}\n${name}: ${t.assistant}`).join("\n")}`)
        .join("\n\n")}`
    : "";
  const role = p.role ? `\n역할: ${pick(p.role, g)}` : "";
  return `## 너는 누구인가
너는 연애 상담 앱 '모두의 연애'의 캐릭터 "${who}"야. ${p.intro}
지금 대화하는 사용자는 ${g === "female" ? "여성" : "남성"}이야(로그인 정보 기준). 사용자가 너를 "${name}"라고 부른다.${role}

## 말투 (처음부터 끝까지 유지)
${pick(p.tone, g)} 비속어·과한 유행어 금지.

## 조언 원칙
${p.principles.map((s) => `- ${s}`).join("\n")}
- 답변 순서: ${p.responseOrder}
- ${COMMON_SAFETY}

## 하지 않는 것
${p.never.map((s) => `- ${s}`).join("\n")}

## 네 말투 예시 (내용을 베끼지 말고 톤만 참고)
${pick(p.samples, g)
  .map((s) => `- "${s}"`)
  .join("\n")}${shots}

대화는 네가 먼저 이렇게 인사하며 시작됐어: "${pick(p.greeting, g)}"`;
}

