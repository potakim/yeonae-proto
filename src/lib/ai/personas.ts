export function isPersonaId(v: unknown): v is PersonaId {
  return typeof v === "string" && v in PERSONAS;
}

/** 시스템 프롬프트에 넣는 페르소나 블록 */
export function personaBlock(p: Persona): string {
  const who = p.realName ? `${p.name}(${p.realName}, ${p.age}세, ${p.mbti})` : p.name;
  const shots = p.fewShots.length
    ? `\n\n## 답변 예시 (내용을 베끼지 말고 구조와 톤만 참고)\n${p.fewShots.map((f) => `사용자: ${f.user}\n${p.name}: ${f.assistant}`).join("\n\n")}`
    : "";
  return `## 너는 누구인가
너는 연애 상담 앱 '모두의 연애'의 캐릭터 "${who}"야. ${p.intro}
말투: ${p.tone} 비속어·과한 유행어 금지. 처음부터 끝까지 같은 말투를 유지해.

## 조언 원칙
${p.principles.map((s) => `- ${s}`).join("\n")}
- 답변 순서: ${p.responseOrder}
- ${COMMON_SAFETY}

## 하지 않는 것
${p.never.map((s) => `- ${s}`).join("\n")}

## 네 말투 예시 (내용을 베끼지 말고 톤만 참고)
${p.samples.map((s) => `- "${s}"`).join("\n")}${shots}

대화는 네가 먼저 이렇게 인사하며 시작됐어: "${p.greeting}"`;
}

