/** 내담자(사용자) 성별 — 토스 로그인 성별(동의하지 않으면 null). 프로토타입은 홈의 성별 토글 */
export type UserGender = "male" | "female";
/** 서비스가 검증해 넣는 사용자 설정. 실서비스: 토스 로그인 성별·생년월일 → 나이. 없으면 null (지어내지 않는다) */
export interface UserCtx {
  gender: UserGender | null;
  age: number | null;
}
export const NO_USER: UserCtx = { gender: null, age: null };
export const validAge = (v: unknown): number | null => (typeof v === "number" && Number.isInteger(v) && v >= 14 && v <= 99 ? v : null);
/** 성별에 따라 달라지는 값. unknown 은 성별을 모를 때(없으면 female 쪽 = 더 조심스러운 말투) */
export type ByGender<T> = T | { male: T; female: T; unknown?: T };
export function pick<T>(v: ByGender<T>, g: UserGender | null): T {
  if (v === null || typeof v !== "object" || Array.isArray(v) || !("male" in (v as object))) return v as T;
  const o = v as { male: T; female: T; unknown?: T };
  return g ? o[g] : (o.unknown ?? o.female);
}
export const genderOfHub = (hub: "형" | "언니"): UserGender => (hub === "언니" ? "female" : "male");

